#!/usr/bin/env python3
"""Build the "Where review comments focus" chart for the Writing papers guide.

Reads   _data/comment_overview.yml   (counts per idea; no comment text)
Writes  _includes/comment-overview.html

The bars are plain HTML/CSS, so they use the site's fonts, stay sharp at any
size, and are read directly by screen readers. Bar lengths and percentages are
computed here from the data file.

Run from the repo root:  python3 scripts/comment_overview.py
Needs:  pyyaml
"""
from pathlib import Path
import html

import yaml

ROOT = Path(__file__).resolve().parents[1]
DATA = yaml.safe_load((ROOT / "_data/comment_overview.yml").read_text())


def main():
    d = DATA
    total = d["n_comments"]
    cats = sorted(d["categories"], key=lambda c: -c["count"])
    top = cats[0]["count"]
    core = sum(c["count"] for c in cats) / total

    rows = "\n".join(
        f'  <li class="co-row">'
        f'<span class="co-label">{html.escape(c["label"])}</span>'
        f'<span class="co-track" aria-hidden="true"><span class="co-bar" style="width: {100 * c["count"] / top:.1f}%"></span></span>'
        f'<span class="co-value">{c["count"] / total:.0%}</span>'
        f'</li>'
        for c in cats
    )
    out = f"""{{%- comment -%}} Generated by scripts/comment_overview.py from _data/comment_overview.yml. Edit those, not this. {{%- endcomment -%}}
<section class="comment-overview" aria-labelledby="co-title">
<h3 id="co-title">Where review comments focus</h3>
<p class="co-lede">Of {d["n_comments"]} review comments on {d["n_drafts"]} lab drafts ({d["years"]}), about {core:.0%} concerned the six ideas above.</p>
<ol class="co-chart">
{rows}
</ol>
</section>
"""
    (ROOT / "_includes/comment-overview.html").write_text(out)
    print("Wrote _includes/comment-overview.html")


if __name__ == "__main__":
    main()
